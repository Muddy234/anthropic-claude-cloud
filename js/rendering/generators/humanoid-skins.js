    function registerAllMonsters() {
        if (typeof AnimationGeneratorRegistry !== 'undefined' && AnimationGeneratorRegistry.registerMonster) {
            for (var name in monsterMappings) {
                if (monsterMappings.hasOwnProperty(name)) {
                    AnimationGeneratorRegistry.registerMonster(name, monsterMappings[name]);
                }
            }
        } else {
            // Defensive: push to pending queue
            window.AnimationGeneratorRegistry = window.AnimationGeneratorRegistry || { _pending: [], _pendingMonsters: [] };
            window.AnimationGeneratorRegistry._pendingMonsters = window.AnimationGeneratorRegistry._pendingMonsters || [];
            for (var name in monsterMappings) {
                if (monsterMappings.hasOwnProperty(name)) {
                    window.AnimationGeneratorRegistry._pendingMonsters.push({ name: name, config: monsterMappings[name] });
                }
            }
        }
    }

