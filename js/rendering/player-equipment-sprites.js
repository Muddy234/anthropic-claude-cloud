// Helper to get equipment sprite
function getEquipmentSprite(equipmentId, direction) {
    const equipment = EQUIPMENT_SPRITES[equipmentId];
    if (!equipment) return null;

    const dirData = equipment.directions[direction] || equipment.directions.down;
    return {
        name: `${equipmentId}_${direction}`,
        width: equipment.width,
        height: equipment.height,
        pixels: dirData.pixels,
        palette: equipment.palette,
        offsetX: dirData.offsetX || 0,
        offsetY: dirData.offsetY || 0
    };
}

// Make available globally
if (typeof window !== 'undefined') {
    window.EQUIPMENT_SPRITES = EQUIPMENT_SPRITES;
    window.getEquipmentSprite = getEquipmentSprite;
}
